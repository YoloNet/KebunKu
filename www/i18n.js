/* t(kunci, ganti) — ambil teks untuk bahasa semasa (window.__bahasa, lalai
   "ms"). Jika kunci tiada dalam bahasa semasa, jatuh ke ms; jika tiada
   dalam kedua-duanya, kembalikan "" (jangan sekali-kali paparkan kunci
   mentah atau "undefined"). ganti ialah objek {nama: nilai} untuk
   parameter {nama} dalam teks. */
function t(kunci, ganti) {
  var lang = (typeof window !== "undefined" && window.__bahasa) ? window.__bahasa : "ms";
  var kamus = (typeof I18N !== "undefined" && I18N[lang]) ? I18N[lang] : I18N.ms;
  var s = kamus[kunci];
  if (s === undefined) s = I18N.ms[kunci];
  if (s === undefined) { try { console.warn("KebunKu i18n: kunci tiada:", kunci); } catch (e) {} return ""; }
  if (ganti) {
    Object.keys(ganti).forEach(function (k) { s = s.split("{" + k + "}").join(String(ganti[k])); });
  }
  return s;
}

